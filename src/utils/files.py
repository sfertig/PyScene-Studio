def gen_project_lists():
    path = get_save_dir_path()
    folders =  os.listdir(path)
    projects = {}
    for folder in folders:
        projects[folder] = path+"/"+folder
    return projects

def check_name(text):
    _text = text
    #make the text folder safe
    for char in ["\\", "/", ":", "*", "?", "\"", "<", ">", "|", ".", " ", "#", "%", "$", "&", "@", "!", "^"]:
        _text = _text.replace(char, "_")
    return _text

